-- خبرٌ يُكتب مرتين أو لا يُكتب أصلاً.
--
-- المدير جدول خبرين من هاتفه على 4G: نجح الأول، وردّ الثاني «تعذّر الحفظ:
-- AbortError: Fetch is aborted». والقاعدة بريئة — لا مؤرِّخ على الجدول ولا
-- عملٌ ثقيل، والإدراج تافه. المهلة اثنتا عشرة ثانية، والشبكة لم تُسعفها.
--
-- والأسوأ من الضياع أنّ الإجهاض لا يقول شيئاً: الطلب قد يكون وصل والتزم
-- بينما تخلّى المتصفح عن انتظار الجواب. فمن يُعيد الضغط يُجدول الخبر مرتين،
-- ويصل الناس مرتين، وإشعارٌ أُرسل لا يُستردّ.
--
-- فمفتاحٌ يولده المتصفح مع أول محاولة ويُعاد به في كل محاولة بعدها. فإن كانت
-- الأولى قد وصلت، ترتدّ الثانية على الفهرس الفريد بدل أن تُنشئ صفّاً ثانياً —
-- وإعادة المحاولة تصير آمنة، فتصير تلقائية.
begin;

alter table announcements
  add column if not exists client_key uuid;

-- جزئيّ: الصفوف القديمة كلها بلا مفتاح، ولو كان الفهرس كاملاً لتصادمت على null.
create unique index if not exists announcements_client_key
  on announcements (client_key)
  where client_key is not null;

commit;
