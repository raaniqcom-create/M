-- ═══ مدينةُ الطلبِ الساقط تُترك فارغةً ═══════════════════════════════════
--
-- «غير المدينة الى فارغة افضل» — صاحبُ المنصّة، ١٩ أيلول.
--
-- ── ولماذا هو أفضل ──────────────────────────────────────────────────────
--
-- `20261003` كتبت «الرمادي» في الطلبات الثماني لأنّ العمودَ يمنع الفراغ —
-- فحصُ `attnotnull` وقع على `true`. وهي قيمةٌ افتراضيّةٌ لا معلومة: مدينتُه
-- لم تصل أصلاً.
--
-- **وخبرٌ خاطئٌ أسوأُ من خبرٍ ناقص.** المشغّلُ يقرأ «الرمادي» فيبني عليها —
-- يرتّب الطلباتِ بها، ويُقدّر قربَها، وقد يعتمدها كما هي. والفراغُ يقول
-- «لا أعرف» فيُسأل عنه.
--
-- ── والفراغُ نصٌّ فارغٌ لا NULL ──────────────────────────────────────────
--
-- العمودُ يمنع NULL، وتليينُه يفتح البابَ لكلّ صفٍّ قادمٍ في الجدول — وهو
-- ثمنٌ كبيرٌ لثماني صفوفٍ مؤقّتة. والنصُّ الفارغ يمرّ من الحارس ويُعرض فراغاً.
--
-- ولا يضرّ ما دام الطلبُ معلَّقاً: الإشعارُ والجدولُ ولوحةُ المدن كلُّها على
-- المعتمد وحدَه. واستمارةُ الإدارة تُلزم باختيار مدينةٍ من القائمة
-- (`AdminStationForm.tsx:27`) — فلا يُعتمد الطلبُ إلّا وقد صارت له مدينةٌ حقيقيّة.
begin;

do $$
declare
  n int;
begin
  begin
    update public.stations
       set city = ''
     where status = 'pending'
       and name like '%⚠️ تسجيل لم يكتمل%'
       and city = 'الرمادي';
    get diagnostics n = row_count;
    raise notice 'طلباتٌ فُرّغت مدينتُها: %', n;
  exception
    -- العمودُ قد يحمل قيداً لا يقبل الفراغ — فتُترك كما هي ويُقال، ولا يسقط
    -- الترحيلُ على تجميلِ حقلٍ في ثماني صفوفٍ مؤقّتة.
    when check_violation or not_null_violation then
      raise notice 'العمودُ يمنع الفراغ — تُركت المدينةُ كما هي.';
  end;
end $$;

-- ولا يُمسّ صفٌّ آخر: الشرطُ ثلاثةٌ معاً — معلَّقٌ، واسمُه علامةُ العطب،
-- ومدينتُه الافتراضيّةُ التي كتبناها نحن.
do $$ begin
  assert not exists (
    select 1 from public.stations
     where city = '' and (status <> 'pending' or name not like '%⚠️%')
  ), 'فُرّغت مدينةُ صفٍّ ليس من طلبات العطب';
end $$;

commit;
