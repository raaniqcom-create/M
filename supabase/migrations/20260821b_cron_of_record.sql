-- الدورات المجدولة تُوثَّق حيث يمكن استعادتها.
--
-- المنصّة تعمل بثلاث دورات، وكلّها أُدخلت بيد في لوحة Supabase ولا أثر لها في
-- أي ملف. فلو استُعيد المشروع من هذا المستودع لاختفت الثلاث صامتةً: لا إشعار
-- وقود، ولا رسائل ملّاك، ولا مسح لحالة ازدحام قديمة — والمنصّة تبدو سليمة.
--
-- وهذا نفس الخطر الذي كُتبت من أجله 20260817f: مخطّطٌ لا يصفه المستودع.
--
-- ويُضاف الرابع: تلخيص سجلّ الإشعارات ثم حذف تفصيله. يبدأ الليلة بعد خروج
-- المحطات من الدوام، ولا يمسّ شيئاً أحدث من ثلاثين يوماً — فأول ثلاثين ليلة
-- لا يحذف صفّاً واحداً، ثم يُبقي الحجم ثابتاً إلى الأبد.
begin;

-- تُحذف أولاً بالاسم: unschedule تُخطئ لو لم تكن موجودة، وschedule تُنشئ نسخة
-- ثانية لو كانت. فالحذف المتسامح ثم الإنشاء هو الشكل الوحيد القابل للإعادة.
select cron.unschedule(jobid) from cron.job where jobname = 'rollup-notifications';

select cron.schedule(
  'rollup-notifications',
  -- ٢٣:٣٠ بتوقيت بغداد = ٢٠:٣٠ UTC. بعد إغلاق آخر محطة، وقبل دورة الصباح.
  '30 20 * * *',
  $$select public.rollup_notifications(30)$$
);

commit;

