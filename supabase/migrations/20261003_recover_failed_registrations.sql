-- ═══ إتمامُ طلباتٍ سقطت: تُصنع معلَّقةً كي لا يضيع أصحابُها ═══════════════
--
-- «المحطات عملوا تسجيل ففشل فخرجوا من المحطة التقنية بصورة نهائية. اريد اتمام
--  طلب تسجيلهم و اظهارهم في الطلبات المعلقة» — صاحبُ المنصّة، ١٩ أيلول.
--
-- ── ما وقع ──────────────────────────────────────────────────────────────
--
-- من ١٥ أيلول ٢٠:١٢ إلى اليوم كان `insert ... returning` يُرفض بسياسةِ قراءة
-- (أُصلح في 20261001). فكلُّ من سجّل رأى «تعذّر حفظ بيانات المحطة» وانصرف،
-- ولم يصل لوحةَ الطلبات منه أحد: القاعدةُ فيها صفرُ صفٍّ معلَّق — تسعٌ وأربعون
-- معتمدة وأربعٌ وثلاثون مرفوضة، ولا ثالثَ لهما.
--
-- ── وتفاصيلُهم لم تُحفظ ─────────────────────────────────────────────────
--
-- الاسمُ والعنوانُ والإحداثيّاتُ كانت في متصفّح صاحبها حتى لحظة الإدراج،
-- والإدراجُ هو الذي سقط. فلا يُخترع لهم اسمٌ ولا موقع: يُكتب صراحةً أنّ
-- التفاصيل تُؤخذ بالاتصال، ويبقى الصفُّ **معلَّقاً** حتى يُراجَع.
--
-- ── ولماذا صفٌّ لا قائمةٌ جانبيّة ───────────────────────────────────────
--
-- لأنّ مسارَ المتابعة قائمٌ ومجرَّب: «📋 طلبات المحطات» فيها الاعتمادُ والرفضُ
-- والتواصلُ بواتساب وسجلُّ القرار. وقائمةٌ ثانيةٌ بمسارٍ ثانٍ تُنسى.
--
-- والمعلَّقُ لا يظهر لأحد: `stations: public read approved` تحصره في المعتمد،
-- فلا يُرى في التطبيق ولا في الخريطة ولا في جدول التوزيع.
--
-- ── وحارسُ الاعتماد بالسهو ──────────────────────────────────────────────
--
-- الاسمُ يبدأ بـ«⚠️» ويقول «لم يكتمل»، والعنوانُ يقول «اتّصل بصاحبها».
-- فمن فتح الطلبَ عرف قبل أن يضغط. والإحداثيّاتُ مركزُ مدينة الرمادي لا صفرٌ:
-- صفرٌ يضع المحطةَ في المحيط الأطلسيّ فتكسر حسابَ المسافات إن اعتُمدت سهواً.
begin;

-- ــ و«المدينة» لا تُختلق ــــــــــــــــــــــــــــــــــــــــــــــــــ
--
-- مدينتُه لم تصل، وكتابةُ «الرمادي» عنها تُلبس الطلبَ خبراً ليس فيه — فيقرؤه
-- المشغّلُ ويبني عليه. فتُترك فارغةً إن سمح العمود، ولا يُكتب فيها إلّا حين
-- يمنع العمودُ الفراغ — و`city` و`kind` أُضيفا في القاعدة الحيّة لا في
-- المستودع، فيُسأل الفهرسُ ولا يُفترض. و`kind` تُترك لافتراضها.
insert into public.stations (owner_id, name, address, city, phone, lat, lng, status)
select
  u.id,
  '⚠️ تسجيل لم يكتمل — 0' || substring(u.email from 2 for 10),
  'التفاصيل لم تصل — اتّصل بصاحبها',
  case
    when (select a.attnotnull from pg_attribute a
           where a.attrelid = 'public.stations'::regclass and a.attname = 'city')
    then 'الرمادي'
    else null
  end,
  '0' || substring(u.email from 2 for 10),
  33.4258,
  43.3089,
  'pending'
from auth.users u
where u.email ~ '^p[0-9]{10}@muhta\.app$'
  and u.created_at >= timestamptz '2026-09-15 00:00:00+00'
  and not exists (select 1 from public.stations s where s.owner_id = u.id)
  and not exists (select 1 from public.car_washes w where w.owner_id = u.id);

do $$
declare
  made int;
  leaked int;
begin
  select count(*) into made from public.stations
   where status = 'pending' and name like '⚠️ تسجيل لم يكتمل%';
  raise notice 'طلباتٌ أُنشئت: %', made;

  -- ولا يُرى منها شيءٌ لأحد: المنظورُ العامُّ على المعتمد وحدَه.
  select count(*) into leaked from public.stations_public
   where name like '⚠️%';
  assert leaked = 0, 'طلبٌ معلَّقٌ ظهر في المنظور العامّ';

  -- ولكلٍّ صاحبُه الحقيقيّ — فحين يُعيد التسجيل بكلمة مروره يجد محطتَه.
  assert not exists (
    select 1 from public.stations
     where name like '⚠️ تسجيل لم يكتمل%' and owner_id is null
  ), 'طلبٌ بلا صاحب';
end $$;

commit;
