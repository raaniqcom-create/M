-- ═══ دوامٌ موحّد: 07:00 – 20:00 ═════════════════════════════════════════════
--
-- «عدّل الآن مواعيد الافتتاح والإغلاق لكلّ المحطات باستثناء من هي 24 ساعة، من
-- الساعة 7:00 صباحاً حتى الساعة 8:00 مساءً» — صاحبُ المنصّة، ١٨ أيلول.
--
-- القياسُ قبل الكتابة: ثمانٍ وأربعون محطةً غيرُ ٢٤ ساعة، منها **اثنتا عشرةَ على
-- 07:00–20:00 أصلاً**. فالتغييرُ يمسّ ستّاً وثلاثين: ثمانٍ وعشرون تفتح قبل
-- السابعة، وسبعٌ وعشرون تغلق بعد الثامنة مساءً، وخمسٌ نافذتُها أضيقُ فتتّسع.
--
-- ── ولماذا الافتراضُ معها ────────────────────────────────────────────────
--
-- استمارتا التسجيل (StationRegisterForm و AdminStationForm) لا ترسلان دواماً
-- إطلاقاً — تلتقطانه من افتراض العمود. فلو صُحّحت القائماتُ وحدَها لَوُلدت كلُّ
-- محطةٍ جديدةٍ على 06:00–22:00 وعاد التفاوتُ من حيث أُغلق.
--
-- ── وما يعنيه هذا للناس ─────────────────────────────────────────────────
--
-- خارج الدوام تبقى المحطةُ في القائمة، لكنّ وقودَها لا يُحسب متوفّراً
-- (`isOffered` تشترط `isOpenNow`)، ولا يخرج إشعارُها، وتسقط من شاشات السيارة
-- ومن فلتر «المفتوحة الآن». ورسائلُ `owner-daily` تنتقل معها: تحيّةُ الصباح من
-- السادسة إلى السابعة، وشكرُ الإغلاق من العاشرة مساءً إلى الثامنة.
--
-- ولا يُحرَس شيءٌ من هذا: `stations_guard` لا يثبّت هذه الأعمدة، فصاحبُ المحطة
-- يردّ دوامَه من لوحته متى شاء — وهي بيانات لا سياسة.
begin;

-- ── ١ · القائمات ─────────────────────────────────────────────────────────
-- والـ٢٤ ساعةً تُستثنى بنصّ الطلب. ولا أثرَ للدوام عليها أصلاً:
-- `station_open_now` تردّ true قبل أن تنظر في النافذة.
update public.stations
   set opens_at = '07:00', closes_at = '20:00'
 where not is_24h
   and (opens_at <> '07:00' or closes_at <> '20:00');

-- ── ٢ · والمولودةُ غداً ──────────────────────────────────────────────────
alter table public.stations
  alter column opens_at  set default '07:00',
  alter column closes_at set default '20:00';

-- ── ٣ · يسقط الترحيلُ هنا لا الشاشةُ غداً ────────────────────────────────
do $$
declare
  o text;
  c text;
begin
  assert not exists (
    select 1 from public.stations
     where not is_24h and (opens_at <> '07:00' or closes_at <> '20:00')
  ), 'بقيت محطةٌ غيرُ ٢٤ ساعةٍ خارج 07:00–20:00';

  select column_default into o from information_schema.columns
   where table_schema = 'public' and table_name = 'stations' and column_name = 'opens_at';
  select column_default into c from information_schema.columns
   where table_schema = 'public' and table_name = 'stations' and column_name = 'closes_at';
  assert o like '%07:00%', format('افتراضُ opens_at لم يُضبط: %s', coalesce(o, 'null'));
  assert c like '%20:00%', format('افتراضُ closes_at لم يُضبط: %s', coalesce(c, 'null'));
end $$;

commit;
