-- ═══ الحالةُ تحمل يومَها ═══════════════════════════════════════════════════
--
-- نُشرت حالةٌ الساعةَ 23:54 تقول «جدول الغد»، ومضى منتصفُ الليل بعدها بستّ
-- دقائق — فصارت تقول عن جدول **اليوم** إنّه جدولُ الغد. وصاحبُ المنصّة رآها:
-- «و مكتوب جدول الغد هو جدول اليوم!».
--
-- والعلّةُ بنيويّة لا إملائيّة: نصُّ الحالة ثابتٌ في القاعدة والزمنُ يجري
-- تحته. فكلُّ حالةٍ عن يومٍ بعينه تكذب بعد ساعات، ولا يُنقذها تصحيحٌ يدويٌّ
-- لأنّ من يكتبها ليس حاضراً حين تُقرأ.
--
-- فيُخزَّن **اليومُ** لا الكلمة، وتُحسب الكلمةُ عند القراءة من تقويم بغداد
-- (`lib/stories.ts`). و«{اليوم}» علامةٌ في النصّ كعلامة «{المدينة}» في اعتذار
-- الجدول — تصير «اليوم» أو «غداً» أو اسمَ اليوم، بحسب متى فُتحت.
--
-- ويُطوى ما مضى يومُه: حالةٌ عن جدولٍ انقضى ليست خبراً ناقصاً بل خبرٌ خاطئ.
alter table public.platform_stories
  add column if not exists for_date date;

comment on column public.platform_stories.for_date is
  'اليومُ الذي تتحدّث عنه الحالة. «{اليوم}» في النصّ تُحسب منه عند القراءة، وما مضى يومُه لا يُعرض.';

do $$ begin
  assert exists (
    select 1 from information_schema.columns
     where table_schema = 'public' and table_name = 'platform_stories' and column_name = 'for_date'
  ), 'for_date لم يُضف';
end $$;
