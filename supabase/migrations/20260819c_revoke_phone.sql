-- الجزء الثاني: نزع الامتيازات.
--
-- ⚠️ لا يُشغَّل إلا **بعد** أن يصل الموقع الجديد إلى الناس. سببه أن القراءات
-- العامة اليوم `select('*')`، ونزع امتياز عمود يجعل النجمة تفشل كلها — فتنكسر
-- قائمة المحطات في كل متصفح يحمل النسخة القديمة، لا أن يُخفى رقم.
--
-- وبعده: من يفتح صفحة كانت محمّلة قبل النشر يرى خطأً حتى يُحدِّث. وذلك مقبول
-- ومحدود؛ أما تشغيل هذا قبل النشر فيكسر الجميع دفعةً واحدة.
--
-- ولماذا نزع الامتياز أصلاً: RLS تحرس **الصفوف لا الأعمدة**، وسياسة القراءة
-- `using (status = 'approved')` بلا قيد عمود. فأيّ أحد يطلب ?select=phone على
-- الجدول يحصل على كل الأرقام مهما أخفت الواجهة. وامتيازات الأعمدة تُنفَّذ فعلاً.
begin;

revoke select (phone, contact_name) on public.stations from anon;

-- المالك والإدارة يقرآن الرقم من الجدول نفسه: صفوفهما تمرّ بسياسات
-- «owner read own» و«admin»، وهما دور authenticated لا anon.

commit;
