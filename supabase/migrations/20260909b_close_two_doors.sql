-- بابان مفتوحان يُغلقان: تغذيةُ محطةٍ يربطها من شاء، ومسارُ من صوّت.
--
-- خرجا من فحصٍ كاملٍ للنظام أُجري في ٢٠٢٦-٠٩-٠٨، ومرّ كلُّ ادّعاءٍ فيه على
-- مشكّكٍ مهمّتُه نقضُه. وكلاهما من الشكل نفسِه: سياسةٌ كُتبت حين كان الجدول
-- أضيقَ، ثمّ اتّسع الجدولُ ولم تُراجَع السياسة.

------------------------------------------------------------------------------
-- ١ · لا يربط أحدٌ هاتفَه بتغذية محطةٍ ليست له
--
-- `device_tokens` فيها `station_id`: به يصل صاحبَ المحطة ما يخصّ محطتَه.
-- والسياسةُ تحرس `is_admin` ولا تحرس `station_id` (20260816_a_add.sql:26).
-- و`claim_owner_device` تتحقّق من الملكيّة — لكنّها ليست الكاتبَ الوحيد: المنحُ
-- للدور العامّ قائم، فطلبٌ مباشرٌ بمفتاح anon — وهو مطبوعٌ في حزمة كلّ زائر —
-- يكتب `station_id` لأيّ محطةٍ شاء ويستقبل تغذيتَها.
--
-- والحارسُ سطرٌ واحد: من أراد الحقلَ يمرّ بالدالّة التي كُتب فحصُها لأجله.
-- و`components/NativePush.tsx` لا يرسل الحقلَ أصلاً — يرسل `{token, platform}`
-- وحدَهما — فلا مسارٌ مشروعٌ ينكسر.
------------------------------------------------------------------------------
drop policy if exists "device_tokens: public insert" on device_tokens;
create policy "device_tokens: public insert" on device_tokens
  for insert to public
  with check (is_admin is not true and station_id is null);

------------------------------------------------------------------------------
-- ٢ · إحداثيّاتُ من صوّت ليست عامّة
--
-- «traffic_votes: public read» بـ`using (true)` كُتبت والجدولُ ثلاثةُ أعمدة:
-- المحطةُ والمستوى والوقت. ثمّ أضاف 20260819b أربعةً — `device_id` و`source`
-- و`lat` و`lng` — ولم تُراجَع السياسة.
--
-- و`device_id` معرّفٌ ثابتٌ لهاتفٍ بعينه. فالجدولُ مقروءاً بمفتاح anon يعطي
-- **مسارَ إنسانٍ**: أين وقف، وفي أيّ ساعة، وكم مرّة. وذلك أخطرُ ما في هذه
-- القاعدة كلِّها، لأنّه لا يخصّ محطةً بل شخصاً لم يُسأل.
--
-- والعلاجُ امتيازُ أعمدةٍ لا سياسة — الطريقةُ نفسُها التي حجبت `stations.phone`
-- في 20260819d، وهي التي عملت هناك بعد أن فشل نزعُ الأعمدة وحدَه.
--
-- وما يُقرأ فعلاً من هذه الأعمدة: `station_traffic_avg` و
-- `station_product_traffic` تقرآن `station_id` و`level` و`product` و
-- `created_at` وحدَها (20260903_runs_out_at.sql:95 و:128)، وهما منظوران
-- يعملان بامتيازات مالكهما فلا يمسّهما هذا. و`cast_traffic_vote` تكتب ولا
-- تقرأ. فلا شيءَ في المنصّة يفقد عموداً.
------------------------------------------------------------------------------
revoke select on public.traffic_votes from anon, authenticated;

grant select (id, station_id, level, product, created_at)
  on public.traffic_votes to anon, authenticated;

