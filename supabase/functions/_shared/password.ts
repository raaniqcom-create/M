/** كلمةُ مرورٍ أوّليّةٌ لحساب محطة — عشوائيّةٌ لا مشتقّة.
 *
 *  ── ما كان قبلها ─────────────────────────────────────────────────────────
 *
 *  كان المسارانِ اللذانِ يُنشئان حسابَ صاحب المحطة — بوتُ تلغرام ونقلُ الرقم —
 *  يكتبان `muhta` + آخرَ أربعةِ أرقامٍ من رقم المحطة. واسمُ الدخول هو الرقمُ
 *  نفسُه (`p<digits>@muhta.app`). فالنصفان علنيّان: ثلاثٌ وعشرون محطةً من
 *  أربعين تنشر رقمَها في `stations_public`، والباقياتُ تُفتح أرقامُها لأيّ
 *  زائرٍ عبر `station_phone_for` — وحارسُها إرشاديٌّ باعترافِ هجرته نفسِها.
 *
 *  فمن قرأ رقماً على شاشته دخل كصاحب المحطة. وذلك يفتح قلبَ التوفّر على
 *  اللوحة العامّة، ويفتح — عبر `callerMayAnnounce` في notify/index.ts:542 —
 *  دفعَ «وصل الوقود» إلى كلّ مشتركي المدينة **باسم المنصّة**. وهو نقضٌ لأصل
 *  ما تبيعه هذه المنصّة: أن يُصدَّق خبرُها.
 *
 *  ── ولماذا هذه الحروف ────────────────────────────────────────────────────
 *
 *  الكلمةُ تُملى في الهاتف وتُكتب على ورقة. فلا `0` ولا `O`، ولا `1` ولا `l`
 *  ولا `I` — حروفٌ تُقرأ حرفين. وعشرةُ رموزٍ من أبجديّةٍ من إحدى وثلاثين
 *  تعطي نحوَ خمسين بتاً، وهو ما يفوق التخمينَ بفارقٍ لا يُدرَك.
 *
 *  و`crypto.getRandomValues` لا `Math.random`: الثانيةُ تُتوقَّع من مخرجاتها.
 *  والقسمةُ المتحيّزة تُرفَض لا تُقبل — بايتٌ فوق ٢٤٩ يُطرح ويُسحب غيرُه، فلا
 *  يصير أوّلُ ستّةِ رموزٍ أكثرَ ورودًا من غيرها. */
const SAFE = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';

export function newPassword(len = 10): string {
  const out: string[] = [];
  while (out.length < len) {
    const bytes = new Uint8Array(len);
    crypto.getRandomValues(bytes);
    for (const b of bytes) {
      // ٣١ × ٨ = ٢٤٨: ما فوقها يُطرح كي يبقى التوزيع مستوياً.
      if (b >= 248) continue;
      out.push(SAFE[b % SAFE.length]);
      if (out.length === len) break;
    }
  }
  return out.join('');
}
