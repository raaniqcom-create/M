// المحطاتُ الحكوميّة بأسمائها وأماكنها الرسميّة — كما يكتبها كتابُ الفرع وكما
// تكتبها القناة، وكما تُسمّى في المنصّة.
//
//   node scripts/test-official-stations.mjs
//
// الأسطرُ أدناه من جدول ١٥ و١٦ أيلول كما وصل حرفاً: الاسمُ ثمّ المدينةُ ثمّ
// بقايا الوقود الآخر في خانةٍ واحدة.
import assert from 'node:assert/strict';
import { officialFor } from '../lib/officialStations.ts';
import { matchLine } from '../lib/schedule.ts';

let n = 0;
const ok = (label, fn) => {
  fn();
  n++;
  console.log(`  ✓ ${label}`);
};

console.log('من كتاب الفرع:');
for (const [raw, name, city] of [
  ['طليحة الحكومية الرمادي وكاز', 'طليحة', 'الرطبة'],
  ['الغوطة الرطبة وكاز', 'الغوطة', 'الرطبة'],
  ['طريبيل الحكومية الرطبة', 'طريبيل', 'الرطبة'],
  ['الرطبة القديمة الحكومية الرطبة', 'الرطبة القديمة', 'الرطبة'],
  ['الرمادي الجديدة الحكومية (الأمن) الرمادي', 'الرمادي الجديدة', 'الرمادي'],
  ['الرمادي السريع الحكومية الرمادي وكاز', 'الرمادي السريع', 'الرمادي'],
  ['الرمادي القديمة الحكومية (السينما) الرمادي', 'الرمادي القديمة', 'الرمادي'],
  ['المحمديات الحكومية الرمادي', 'المحمديات', 'الرمادي'],
  ['الحبانية القديمة الحكومية الخالدية', 'الحبانية القديمة', 'الحبانية'],
  ['الجبل الحكومية البغدادي وكاز', 'الجبل', 'البغدادي'],
  ['الحقلانية الحكومية الحقلانية وكاز ونفط أبيض', 'الحقلانية', 'الحقلانية'],
  ['عانة الجديدة الحكومية عانة وكاز', 'عنة الجديدة', 'عنة'],
  ['البساط الأخضر الحكومية القائم', 'البساط الأخضر', 'العبيدي'],
  ['الصقلاوية الحكومية الصقلاوية وكاز', 'الصقلاوية', 'الصقلاوية'],
  ['الشاكر عامرية الفلوجة', 'الشاكر', 'عامرية الفلوجة'],
  ['الخالدية الخالدية', 'الخالدية', 'الخالدية'],
  ['الرمانة الحكومية الرمانة', 'الرمانة', 'الرمانة'],
]) {
  ok(`«${raw}» → ${name} · ${city}`, () => {
    const m = matchLine(raw, []);
    assert.ok(m.name.includes(name), `«${raw}» صارت «${m.name}»`);
    assert.equal(m.city, city, `مدينةُ «${raw}»`);
    assert.ok(m.name.startsWith('محطة تعبئة وقود'), `الاسمُ الرسميُّ كاملاً، لا «${m.name}»`);
  });
}

console.log('من القناة، بالمعلم:');
ok('«الامن» عنوانٌ لمحطةٍ واحدة', () => {
  assert.equal(officialFor('الامن')?.name, 'محطة تعبئة وقود الرمادي الجديدة');
});
ok('«5 كيلو» عنوانُ اثنتين فلا يُحسم', () => {
  assert.equal(officialFor('5 كيلو'), null);
});
ok('«الجزيرة» نصفُ عنوان', () => {
  assert.equal(officialFor('الجزيرة'), null);
});

console.log('الامتناع:');
for (const raw of [
  'الكعبيات الحكومية القائم',
  'الكرابلة الحكومية القائم',
  'الوئام الخالدية',
  'الكوثر الخالدية',
  'جبل النور هيت',
  'البغدادية الكرمة',
  'الفرات الحكومية الفرات وكاز',
  'مركز توزيع الرمادي الرمادي',
]) {
  ok(`«${raw}» ليست محطةً حكوميّةً من القائمة`, () => {
    assert.equal(officialFor(raw), null, `«${raw}» → ${officialFor(raw)?.name}`);
  });
}

console.log('أسماءُ المنصّة:');
ok('«محطة الخالدية» هي الخالدية المشيدة', () => {
  assert.equal(officialFor('محطة الخالدية')?.address, 'الخالدية');
});
ok('«محطة التل الأخضر» بعنوانها', () => {
  assert.equal(officialFor('محطة التل الأخضر')?.address, 'الجزيرة، البو علي');
});
ok('المسجّلةُ تحتفظ باسمها والمدينةُ رسميّة', () => {
  const m = matchLine('التل الأخضر الرمادي', [
    { id: 'P', name: 'محطة التل الأخضر', lat: null, lng: null, city: 'الرمادي' },
  ]);
  assert.equal(m.stationId, 'P');
  assert.equal(m.name, 'محطة التل الأخضر');
  assert.equal(m.city, 'الرمادي');
});
ok('«تاج الجزيرة الخالدية» لا تُربط بـ«محطة الخالدية»', () => {
  const kh = [{ id: 'K', name: 'محطة الخالدية', lat: null, lng: null, city: 'الخالدية' }];
  assert.equal(matchLine('تاج الجزيرة الخالدية', kh).stationId, null);
  assert.equal(matchLine('الكوثر الخالدية', kh).stationId, null);
  assert.equal(matchLine('الخالدية الخالدية', kh).stationId, 'K');
});

console.log(`\n${n} فحصاً مرّت.`);
