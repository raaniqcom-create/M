// يفحص مطابقةَ أسماء الجدول بقائمة المسح — ومنها تأتي المدينة.
//
//   node scripts/test-schedule-match.mjs
//
// الأسماءُ أدناه **من منشورات القناة نفسِها**، لا من التخيّل. وهي تصل بلهجةٍ
// وبلا كلمة «محطة» وبلا مدينة: «الامن»، «السينما»، «البو يشة». فالمطابقةُ هي
// كلُّ ما يحوّل هذه الكلمةَ إلى محطةٍ لها اسمٌ ومدينةٌ وصفحة.
//
// وأخطرُ ما يُفحص هنا ليس النجاح بل **الامتناع**: مطابقٌ يجد شيئاً دائماً
// أسوأُ من مطابقٍ يقول «لا أعرف» — لأنه يَنسب مدينةً بلا سند، ويستبدل الاسمَ
// الذي كتبته القناةُ باسمٍ آخر، فيقرأ الناسُ خبراً عن محطةٍ لم تُذكر.
import assert from 'node:assert/strict';
import { MATCH_FLOOR, matchLine } from '../lib/schedule.ts';

let n = 0;
const ok = (label, fn) => {
  fn();
  n++;
  console.log(`  ✓ ${label}`);
};

// ــ ما يجب أن يُطابَق ــــــــــــــــــــــــــــــــــــــــــــــــــــــــ
//
// «الامن» أوّلاً: عليها يقوم التطبيعُ كلُّه — همزةُ «الأمن» تُفلطح، و«محطة»
// و«تعبئة» و«وقود» تُسقَط من الاسم الرسميّ الطويل. ولولا ذلك لَما التقيا.
const MATCHED = [
  ['الامن', 'الأمن', 'الرمادي'],
  ['السينما', 'الرمادي القديمة (السينما)', 'الرمادي'],
  ['الصابرين', 'الصابرين', 'الرمادي'],
  ['الاوائل', 'الأوائل', 'الرمادي'],
  ['الواحة الخضراء', 'الواحة الخضراء', 'الرمادي'],
  ['نور الحياة', 'نور الحياة', 'الرمادي'],
  ['مها البادية', 'مها البادية', 'الرمادي'],
  ['الخالدية', 'الخالدية', 'الخالدية'],
];

console.log('مطابقةُ أسماء القناة:');
for (const [raw, needle, city] of MATCHED) {
  ok(`«${raw}» → ${needle} · ${city}`, () => {
    const m = matchLine(raw, []);
    assert.ok(
      m.name.includes(needle),
      `«${raw}» طابقت «${m.name}» ولا تحوي «${needle}»`
    );
    assert.equal(m.city, city, `مدينةُ «${raw}»`);
    assert.ok(m.score >= MATCH_FLOOR, `درجةُ «${raw}» = ${m.score}`);
  });
}

// ــ ومرادفاتُ اللهجة ــــــــــــــــــــــــــــــــــــــــــــــــــــــــ
//
// «السريع البو ريشه» عند الناس هي «محطة الرمادي الحكومية الطريق السريع»
// عندنا — قالها صاحبُ المنصّة. والتشابهُ وحدَه يعطيها ٢٧٫٥ فتسقط دون الحدّ
// بحقّ، فالمرادفُ يرفعها إلى مئةٍ **بلا** أن يُخفَّض الحدُّ لأحدٍ غيرها.
console.log('مرادفاتُ اللهجة:');
for (const raw of ['السريع البو ريشه', 'السريع البريشة', 'البو يشة']) {
  ok(`«${raw}» → الطريق السريع · الرمادي`, () => {
    const m = matchLine(raw, []);
    assert.ok(m.name.includes('الطريق السريع'), `«${raw}» طابقت «${m.name}»`);
    assert.equal(m.city, 'الرمادي');
    assert.equal(m.score, 100, 'المرادفُ تطابقٌ تامّ لا تشابه');
  });
}

// ــ ما يجب ألّا يُطابَق ــــــــــــــــــــــــــــــــــــــــــــــــــــــ
//
// «الواحة الزرقاء» تشترك مع «الواحة الخضراء» في كلمةٍ من كلمتين — ٢٧٫٥ —
// وهو بالضبط قدرُ التشابه الذي كان يجعل «البو يشة» تُطابق «البوذياب». واسمٌ
// مخترَعٌ بالكامل يقف عند الصفر. وفي الحالتين يبقى الاسمُ كما وصل، والمدينةُ
// فارغةً يكتبها إنسان.
console.log('الامتناعُ عن التخمين:');
for (const raw of ['الواحة الزرقاء', 'نور السلام', 'محطة وقود لا وجود لها أبدا']) {
  ok(`«${raw}» لا تُخمَّن`, () => {
    const m = matchLine(raw, []);
    assert.equal(m.name, raw, `«${raw}» استُبدل اسمُها بـ«${m.name}»`);
    assert.equal(m.city, null, `«${raw}» نُسبت إلى «${m.city}» بلا سند`);
    assert.ok(m.score < MATCH_FLOOR, `درجةُ «${raw}» = ${m.score}`);
  });
}

// ــ والدرجةُ المرفوضة تُحفظ ــــــــــــــــــــــــــــــــــــــــــــــــــ
//
// `match_score` عمودٌ للقياس لا للعرض: بلا حفظِ ٢٧٫٥ يبقى سؤالُ «أين يُخطئ
// المطابقُ باستمرار؟» بلا جواب.
ok('الدرجةُ دون الحدّ تُحفظ ولا تُصفَّر', () => {
  assert.ok(matchLine('الواحة الزرقاء', []).score > 0);
});

// ــ والمحطةُ المسجّلة تُربط بالجوار ــــــــــــــــــــــــــــــــــــــــ
//
// إحداثيّاتُ «محطة الحق» من قائمة المسح نفسِها، فمحطةٌ مسجّلةٌ عليها تُربط —
// وحدُّ الخمسمئة متر مقيسٌ في نموذج التسجيل لا مخمَّن.
ok('المسجّلةُ القريبة تُربط، والبعيدةُ لا', () => {
  const here = matchLine('الحق', []);
  assert.equal(here.stationId, null, 'بلا منصّةٍ لا رابط');

  const { la, lo } = { la: 33.4258, lo: 43.3079 }; // محطة الحق — الرمادي
  const near = matchLine('الحق', [{ id: 'S1', name: 'محطة الحق', lat: la, lng: lo }]);
  assert.equal(near.stationId, 'S1');
  assert.equal(near.name, 'محطة الحق', 'الاسمُ المسجّلُ يغلب المسحيّ');

  const far = matchLine('الحق', [{ id: 'S2', name: 'محطة أخرى', lat: 36.34, lng: 43.13 }]);
  assert.equal(far.stationId, null, 'محطةٌ في الموصل لا تُربط بمحطةٍ في الرمادي');
});

console.log(`${n} فحصاً — كلُّها سليمة.`);
