// ما الذي يخرج فعلاً إلى شاشة القفل.
//
//   node scripts/test-announce-body.mjs
//
// فجرَ الرابع من أيلول وصل تسعَ مئةٍ وخمسةً وتسعين جهازاً: «16 محطات في
// الفلوجة والرمادي والخالدية…» — عن **محطةٍ واحدة**. والستّةَ عشرَ لم تكن
// محطات، بل مطابقاتِ تعبيرٍ نمطيّ: ثمانيةُ أسطرِ مدنٍ × وردتَي «محطة» في
// السطر. فطُبعت قائمةُ التوجيه مكان الخبر.
//
// ── ولماذا لا يُحاكى المنطق هنا ─────────────────────────────────────────
//
// بقيةُ اختبارات هذا المجلد تنسخ المنطق في الملفّ، وذلك يكفي حين يكون العطلُ
// في قاعدةٍ تُنسى. وهذا العطلُ من صنفٍ آخر: **الشيفرةُ فعلت غير ما ظنّه
// كاتبُها**. فمحاكاةٌ ثانية تُثبت ظنّي أنا لا ما تفعله الشيفرة.
//
// ولذلك يُقرأ المصدران ويُنتزع منهما نصُّ الدالّتين وتُقوَّمان: `announceBody`
// في lib (تقرؤها اللوحةُ والمعاينة) و`oneLine` في دالّة الحافّة (يقرؤها
// المُرسِل). نسختان لأن الحافّة لا تستورد من lib — والخطرُ أن تفترقا، فيُعاين
// المديرُ نصّاً ويصل الناسَ آخر. وهذا الملفّ يمنعه.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

/** يُنتزع نصُّ دالّةٍ من ملفٍّ ويُقوَّم — بعد نزع تعليقات الأنواع. */
function extract(path, name) {
  const src = readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
  const start = src.indexOf(`function ${name}(`);
  assert.ok(start >= 0, `لم أجد ${name} في ${path} — أعيدت تسميتُها؟`);
  const end = src.indexOf('\n}', start);
  assert.ok(end > start, `لم أجد نهاية ${name} في ${path}`);
  const body = src
    .slice(start, end + 2)
    .replace(/\(([a-zA-Z]+): string\)/g, '($1)')
    .replace(/\): string \{/, ') {');
  // BODY_MAX يُمرَّر: نسخةُ lib تقرؤه من ثابتٍ في ملفّها، ونسخةُ الحافّة
  // تكتب 178 حرفياً. والقيمةُ واحدة، ولو افترقتا لظهر ذلك في حالة الطول.
  return new Function('BODY_MAX', `${body}; return ${name};`)(178);
}

const fromLib = extract('lib/announceTemplates.ts', 'announceBody');
const fromEdge = extract('supabase/functions/notify-favorites/index.ts', 'oneLine');
const named = extract('lib/announceTemplates.ts', 'named');

const BULLET = String.fromCharCode(0x2022);
const NL = String.fromCharCode(10);
// ما كتبه المديرُ في الخانة — وفيه لفظةُ «محطة» أصلاً
const TYPED = 'محطة الرحاب ( شارع الثرثار)';
// وما خُزِّن فعلاً فجرَ الرابع من أيلول: القالبُ ألصق «محطة» ثانيةً أمام
// اسمٍ يبدأ بها — وهي نصفُ سبب الرقم «16»
const DOUBLED = `محطة ${TYPED} — الفلوجة`;
// وما يُخزَّن اليوم بعد البادئة المشروطة
const RAHAB = `${TYPED} — الفلوجة`;
const EIGHT = [
  'الفلوجة', 'الرمادي', 'الخالدية', 'الحبانية',
  'عامرية الفلوجة', 'الكرمة', 'الصقلاوية', 'حصيبة الشرقية',
];

let n = 0;
/** كلُّ حالةٍ تُجرَّب على النسختين معاً، وتُقارَنان — فالافتراقُ عطلٌ بذاته. */
function both(input, expected, what) {
  const a = fromLib(input);
  const b = fromEdge(input);
  assert.equal(a, b, `النسختان افترقتا على «${what}»: lib=«${a}» edge=«${b}»`);
  if (expected !== null) assert.equal(a, expected, what);
  n += 2;
  return a;
}

// ── ١ · الشكلُ الذي أنتج العطل: ثمانيةُ أسطرِ مدنٍ لمحطةٍ واحدة ──────────
{
  const legacy = EIGHT.map((c) => `${BULLET} ${c}: ${DOUBLED}`).join(NL);
  // شاهدُ الجريمة: ثمانيةُ أسطرٍ × وردتَي «محطة» = الرقمُ الذي وصل الناس
  assert.equal((legacy.match(/محطة/g) ?? []).length, 16);
  n++;

  // والتاريخُ لا يُعاد كتابته: الصفُّ القديم يخرج بجملته المضاعفة — لكنه
  // يخرج **جملةً**، لا قائمةَ مناطق.
  const out = both(legacy, DOUBLED, 'ثمانيةُ أسطرٍ متطابقة ← جملةٌ واحدة');
  assert.ok(!/\d/.test(out), 'ولا رقمَ في المتن');
  assert.ok(!out.includes('محطات'), 'ولا «محطات»');
  assert.ok(!out.includes(' و' + 'الرمادي'), 'ولا قائمةَ مدنٍ موصولةٍ بالواو');
  assert.ok(!out.includes('اضغط لعرض'), 'ولا وعدَ صفحةٍ لا تفي');
  assert.ok(out.length <= 178, 'ويسع حدَّ شاشة القفل');
  n += 5;
}

// ── ٢ · الشكلُ الجديد: الجملةُ وحدها، تمرّ كما هي ────────────────────────
both(RAHAB, RAHAB, 'الجملةُ وحدها لا تُمَسّ');

// ── ٢ب · و«محطة» لا تُضاعَف بعد اليوم ───────────────────────────────────
{
  assert.equal(named(TYPED), TYPED, 'اسمٌ يبدأ بـ«محطة» لا يُسبَق بها ثانيةً');
  assert.equal(named('المحطة الحديثة'), 'المحطة الحديثة', 'ولا «المحطة»');
  assert.equal(named('الرحاب'), 'محطة الرحاب', 'ومن كتب الاسمَ مجرّداً يُسبَق مرّةً');
  assert.equal(named('  الرحاب  '), 'محطة الرحاب', 'والفراغُ يُشذَّب');
  n += 4;
}

// ── ٣ · خبرُ المنصّة: أسطرٌ مختلفة، فتبقى كلُّها ─────────────────────────
{
  const notice = ['الإنترنت ينقطع 6:00 صباحاً', 'ويوجد توزيع 6:30 في الرمادي'].join(NL);
  const out = both(notice, null, 'تنبيهُ المنصّة يحفظ سطرَيه');
  assert.ok(out.includes('الإنترنت ينقطع'), 'السطرُ الأوّل باقٍ');
  assert.ok(out.includes('توزيع'), 'والثاني كذلك');
  n += 2;
}

// ── ٤ · محطتان حقاً: تُسمّيان، ولا تُستبدلان بعددٍ ولا بمناطق ────────────
{
  const two = [
    `${BULLET} الفلوجة: محطة الرحاب — الفلوجة`,
    `${BULLET} الرمادي: محطة الأوائل — الرمادي`,
  ].join(NL);
  const out = both(two, null, 'محطتان مختلفتان تبقيان');
  assert.ok(out.includes('الرحاب') && out.includes('الأوائل'), 'الاسمان معاً');
  assert.ok(!/^\d/.test(out), 'ولا يبدأ بعدد');
  n += 2;
}

// ── ٥ · بادئةُ المدينة تُنزع، والشرطةُ لا تُخدَع ─────────────────────────
{
  both(`${BULLET} الكرمة: ${RAHAB}`, RAHAB, 'بادئةُ مدينةٍ واحدة تُنزع');
  // «— الفلوجة» فيها شرطةٌ لا نقطتان، فلا تُقرأ بادئةً
  both(RAHAB, RAHAB, 'الشرطةُ في الجملة ليست بادئة');
  // جملةٌ طويلة فيها نقطتان بعد كلامٍ طويل: لا تُبتَر
  const long = 'وصلت الشحنة اليوم إلى المحطة والصرف مستمر: راجع اللوحة';
  both(long, long, 'نقطتان بعد كلامٍ طويل لا تُعَدّان بادئةَ مدينة');
}

// ── ٦ · الفراغُ لا يُنتج فراغاً ─────────────────────────────────────────
{
  const blank = [``, `   `, ``].join(NL);
  const out = both(blank, null, 'متنٌ فارغ');
  assert.equal(out, '', 'يعود فارغاً لا ينهار');
  n++;
}

// ── ٧ · الطولُ يُقصّ عند حدِّ شاشة القفل ────────────────────────────────
{
  const huge = Array.from({ length: 12 }, (_, i) => `محطة رقم ${i} — الرمادي`).join(NL);
  const out = both(huge, null, 'اثنتا عشرةَ محطةً مختلفة');
  assert.ok(out.length <= 178, `القصُّ عند 178، وطولُه ${out.length}`);
  n++;
}

console.log(`✓ متنُ الإشعار — ${n} تحقّقاً، والنسختان متطابقتان`);
