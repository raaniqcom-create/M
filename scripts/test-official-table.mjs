// قراءةُ الكتاب الرسميّ — على الكتابين اللذين وصلا فعلاً، لا على مخترَع.
//
//   node scripts/test-official-table.mjs
//
// وصل صاحبَ المنصّة «موقف طلبيات المحطات الحكومية والأهلية في محافظة (الانبار)
// ليوم (٢٠٢٦/٩/٩)» — كتابان في يومٍ واحد: مصفى الصمود، ومصفى كركوك. وهما
// منقولان أدناه صفّاً صفّاً.
//
// ── وأخطرُ ما فيه ليس القراءةَ بل ثلاثةٌ ─────────────────────────────────
//
// **التاريخ.** الكتابُ يقوله بنصّه بأرقامٍ مشرقيّة. وليلةَ ٢٠٢٦-٠٩-٠٨ اختلط
// جدولان في تاريخٍ واحدٍ لأنّ التاريخَ كان يُرجَّح بساعة اللصق — فقراءتُه من
// الوثيقة تقتلع ذلك الصنفَ من العطب.
//
// **والمدينة.** «الفلوجة/الصقلاوية» فيها اسمان، كلاهما مدينةٌ في المنصّة.
// والأخصُّ هو المقصود.
//
// **والخانةُ الفارغة.** صفٌّ فيه أربعةُ أعمدةٍ ثلاثتُها شرطات — فلو قُرئت
// الشرطةُ طلبيّةً لَأعلنّا وصولَ كازٍ ونفطٍ أبيضَ لم يُقرَّر لهما شيء.
import assert from 'node:assert/strict';
import {
  cityFromDistrict,
  hasOrder,
  looksLikeOfficialTable,
  readOfficialTable,
  splitCells,
  tableDate,
  tableSource,
  toLatinDigits,
} from '../lib/officialTable.ts';
import { looksLikeSchedule } from '../lib/schedule.ts';

// ــ كتابُ مصفى الصمود — ستّ عشرة محطة، كلُّها بنزين عادي ــــــــــــــــــ
const SUMOUD = `موقف طلبيات المحطات الحكومية والأهلية فى محافظة (الانبار) ليوم (٢٠٢٦/٩/٩ )
يجهز من مصفى الصمود ( اهلي )
ت | المحافظة | القضاء – الناحية – القاطع | اسم المحطة | عادي | محسن | نفط ابيض | زيت الغاز
١ | الانبار | الفلوجة/الحولي الشمالي | رحاب المشيدة | اثنان | ——— | ——— | ———
٢ | الانبار | الفلوجة/شارع ٦٠ | ساسكو المشيدة | واحدة | ——— | ——— | ———
٣ | الانبار | الفلوجة/المركز | الفردوس المشيدة | اثنان/واحدة اعادة | ——— | ——— | ———
٤ | الانبار | الفلوجة/الصقلاوية | الثرثار المشيدة | واحدة | ——— | ——— | ———
٥ | الانبار | عامرية الصمود/المركز | عطارد المشيدة | واحدة | ——— | ——— | ———
٦ | الانبار | الكرمة/الذراع | ذراع دجلة المشيدة | واحدة | ——— | ——— | ———
٧ | الانبار | الخالدية/حصيبة الشرقية | الكوثر المشيدة | واحدة | ——— | ——— | ———
٨ | الانبار | الرمادي/شارع ٦٠ | رماح الانبار المشيدة | واحدة | ——— | ——— | ———
٩ | الانبار | الرمادي/المركز | المسرة المشيدة | واحدة | ——— | ——— | ———
١٠ | الانبار | الرمادي/الجزيرة | الدليم المشيدة | واحدة | ——— | ——— | ———
١١ | الانبار | الرمادي/الجزيرة | اسوار المدينة المشيدة | واحدة | ——— | ——— | ———
١٢ | الانبار | الرمادي/زنكورة | مها البادية المشيدة | واحدة | ——— | ——— | ———
١٣ | الانبار | هيت/طريق خارجي | الغزال المشيدة | واحدة | ——— | ——— | ———
١٤ | الانبار | حديثة/المركز | سيف الانبار المشيدة | واحدة | ——— | ——— | ———
١٥ | الانبار | عنة/طريق خارجي | الهيف المشيدة | واحدة | ——— | ——— | ———
١٦ | الانبار | القائم/طريق تيوان | علوش المشيدة | واحدة | ——— | ——— | ———
المجموع | ١٦/ستة عشر | ١٨/ثمانية عشر
ملاحظة :- حمولات البنزين العادي حصراً ( ٣٦٠٠٠ ) حسب توجيهات شعبة التجهيز`;

// ــ كتابُ مصفى كركوك — ثلاثُ محطات، محسن ــــــــــــــــــــــــــــــــــ
const KIRKUK = `موقف طلبيات المحطات الحكومية والأهلية فى محافظة (الانبار) ليوم (٢٠٢٦/٩/٩ )
يجهز من مصفى كركوك - مستودع البرهم
ت | المحافظة | القضاء – الناحية – القاطع | اسم المحطة | عادي | محسن | نفط ابيض | زيت الغاز
١ | الانبار | الفلوجة/النساف | الفتح المبين المشيدة | ——— | واحدة | ——— | ———
٢ | الانبار | الخالدية/المركز | الخالدية المشيدة | ——— | واحدة | ——— | ———
٣ | الانبار | الرمادي/التأميم | الاوائل المشيدة | ——— | واحدة | ——— | ———`;

// ولا محطاتِ منصّةٍ في الفحص: المطابقةُ بالإحداثيّات تخصّ `matchLine` ولها
// فحصُها. وما يُقاس هنا هو القراءةُ نفسُها.
const NO_PLATFORM = [];

let n = 0;
const ok = (c, w) => { assert.ok(c, w); n++; };
const eq = (a, b, w) => { assert.equal(a, b, w); n++; };

// ── ١ · الأرقامُ المشرقيّة والتاريخ ──────────────────────────────────────
{
  eq(toLatinDigits('٢٠٢٦/٩/٩'), '2026/9/9', 'تحويلُ الأرقام');
  eq(toLatinDigits('٣٦٠٠٠'), '36000', 'وحمولةُ البنزين');
  eq(tableDate(SUMOUD), '2026-09-09', 'التاريخُ من عنوان الكتاب');
  eq(tableDate(KIRKUK), '2026-09-09', 'وكذلك الثاني');
  eq(tableDate('ليوم (9/9/2026)'), '2026-09-09', 'وتُقبل الصيغةُ المقلوبة');
  // **ولا يُخمَّن**: بلا تاريخٍ في النصّ يُردّ null، وزرُّ 📅 يضبطه.
  eq(tableDate('موقف طلبيات بلا تاريخ'), null, 'ولا يُخترع تاريخٌ غيرُ مكتوب');
}

// ── ٢ · المصفى المجهِّز ─────────────────────────────────────────────────
{
  eq(tableSource(SUMOUD), 'مصفى الصمود (اهلي)', 'مصفى الصمود');
  eq(tableSource(KIRKUK), 'مصفى كركوك - مستودع البرهم', 'ومصفى كركوك');
}

// ── ٣ · البوّابة — وهي التمييز ──────────────────────────────────────────
{
  ok(looksLikeOfficialTable(SUMOUD), 'الكتابُ يُعرف');
  ok(looksLikeOfficialTable(KIRKUK), 'والثاني');
  ok(!looksLikeOfficialTable('غدا ان شاء الله البنزين العادي في المحطات التالية'), 'ومنشورُ القناة ليس كتاباً');
  ok(!looksLikeOfficialTable('محطة الحق'), 'ولا اسمُ محطة');
  // قرينةٌ واحدةٌ لا تكفي — «المحافظة» تَرِد في كلامٍ كثير.
  ok(!looksLikeOfficialTable('نحن في المحافظة'), 'وقرينةٌ واحدةٌ لا تكفي');
}

// ── ٤ · الخانةُ الفارغة ─────────────────────────────────────────────────
{
  ok(!hasOrder('———'), 'الشرطةُ الطويلة');
  ok(!hasOrder('-'), 'والقصيرة');
  ok(!hasOrder('ـــــ'), 'والتطويل');
  ok(!hasOrder('   '), 'والفراغ');
  ok(hasOrder('واحدة'), 'وواحدة طلبيّة');
  ok(hasOrder('اثنان/واحدة اعادة'), 'والمركّبةُ طلبيّةٌ واحدة');
}

// ── ٥ · المدينةُ من القضاء/الناحية ──────────────────────────────────────
{
  eq(cityFromDistrict('الفلوجة/الحولي الشمالي'), 'الفلوجة', 'ناحيةٌ غيرُ معروفة → القضاء');
  eq(cityFromDistrict('الرمادي/شارع ٦٠'), 'الرمادي', 'وشارعٌ كذلك');
  // **والأخصُّ يُقدَّم**: كلاهما مدينةٌ في المنصّة، ومن اختار الصقلاوية يريدها.
  eq(cityFromDistrict('الفلوجة/الصقلاوية'), 'الصقلاوية', 'ناحيةٌ معروفة → هي');
  eq(cityFromDistrict('الخالدية/حصيبة الشرقية'), 'حصيبة الشرقية', 'وكذلك حصيبة');
  // وأسماءٌ رسميّةٌ تخالف قائمتَنا.
  eq(cityFromDistrict('عامرية الصمود/المركز'), 'عامرية الفلوجة', 'عامرية الصمود');
  eq(cityFromDistrict('عنة/طريق خارجي'), 'عانة', 'وعنة');
  eq(cityFromDistrict('الكرمة/الذراع'), 'الكرمة', 'والكرمة');
  eq(cityFromDistrict('القائم/طريق تيوان'), 'القائم', 'والقائم');
}

// ── ٦ · الكتابُ كلُّه ───────────────────────────────────────────────────
{
  const t = readOfficialTable(SUMOUD, NO_PLATFORM);
  eq(t.forDate, '2026-09-09', 'تاريخُ الكتاب');
  eq(t.source, 'مصفى الصمود (اهلي)', 'ومصفاه');
  // ستَّ عشرةَ محطةً، لكلٍّ خانةُ عاديٍّ واحدة → ستّةَ عشرَ سطراً لا أكثر.
  eq(t.lines.length, 16, `ستّةَ عشرَ سطراً (وقعت ${t.lines.length})`);
  ok(t.lines.every((l) => l.product === 'gasoline_regular'), 'كلُّها بنزين عادي');
  eq(t.skipped.length, 0, `ولا صفَّ مجهول (وقع ${t.skipped.length}: ${t.skipped[0] ?? ''})`);

  // والمدنُ كما تُقرأ من عمود القضاء.
  const cities = [...new Set(t.lines.map((l) => l.city))].sort();
  ok(cities.includes('الصقلاوية'), 'الصقلاوية بعينها لا الفلوجة');
  ok(cities.includes('حصيبة الشرقية'), 'وحصيبة الشرقية');
  ok(cities.includes('عامرية الفلوجة'), 'وعامرية الصمود بعد ترجمتها');
  ok(cities.includes('عانة'), 'وعنة بعد ترجمتها');
  ok(!cities.includes(null), `ولا مدينةَ مجهولة (${cities.join(' · ')})`);

  // والمجموعُ والملاحظةُ والترويسةُ ليست صفوفاً.
  ok(!t.lines.some((l) => l.name.includes('المجموع')), 'المجموعُ ليس محطة');
  ok(!t.lines.some((l) => l.name.includes('ملاحظة')), 'ولا الملاحظة');
  ok(!t.lines.some((l) => l.name.includes('اسم المحطة')), 'ولا الترويسة');
}

// ── ٧ · والثاني: محسن لا عادي ───────────────────────────────────────────
{
  const t = readOfficialTable(KIRKUK, NO_PLATFORM);
  eq(t.lines.length, 3, 'ثلاثُ محطات');
  ok(t.lines.every((l) => l.product === 'gasoline_premium'), 'كلُّها محسن');
  // **وهذا هو موضعُ الشرطة**: لو قُرئت طلبيّةً لصارت اثنتَي عشرةَ سطراً.
  ok(t.lines.length !== 12, 'ولو قُرئت الشرطةُ طلبيّةً لصارت اثنتَي عشرة');
  eq(t.source, 'مصفى كركوك - مستودع البرهم', 'ومصفاه');
}

// ── ٨ · والفاصلُ يُكتشف ─────────────────────────────────────────────────
{
  eq(splitCells('أ\tب\tج').length, 3, 'جدولة');
  eq(splitCells('| أ | ب | ج |').length, 3, 'وعارضة');
  eq(splitCells('أ   ب   ج').length, 3, 'ومسافتان فأكثر');
  // والمسافةُ الواحدةُ لا تقسم: أسماءُ المحطات فيها مسافات.
  eq(splitCells('اسوار المدينة المشيدة').length, 1, 'واسمٌ فيه مسافاتٌ يبقى واحداً');

  // والكتابُ نفسُه بجدولةٍ بدل العارضة يُقرأ كما هو.
  const tabbed = SUMOUD.replace(/ \| /g, '\t');
  const t = readOfficialTable(tabbed, NO_PLATFORM);
  eq(t.lines.length, 16, `والجدولةُ تُعطي ستّةَ عشرَ أيضاً (وقعت ${t.lines.length})`);
}

// ── ٩ · والمسارُ القديم يدّعي الكتاب — ولهذا يُسأل الجديدُ أوّلاً ────────
//
// كُتب هذا القسمُ أوّلاً يتوقّع أنّ `looksLikeSchedule` لا تعرف الكتاب، فسقط.
// والسببُ أنّ حاشيةَ الكتاب تقول «حسب توجيهات شعبة **التجهيز**» — و«تجهيز»
// إحدى قرائن الصياغة في `SCHEDULE_HINTS`. وفيه أسماءُ وقودٍ بالطبع.
//
// **فلو لُصق الكتابُ اليومَ لالتقطه المحلّلُ القديم**: يقرأ كلَّ صفٍّ سطراً
// واحداً بمنتجٍ واحد، فتصير «١ | الانبار | الفلوجة/الحولي الشمالي | رحاب
// المشيدة | اثنان | ——— …» اسمَ محطةٍ واحداً طويلاً.
//
// ولذلك يُسأل البابُ الجديدُ **قبل** القديم في التوجيه — لا بعده. وهذا القسمُ
// يحرس ذلك الترتيبَ بأن يُثبت أنّ الاثنين يدّعيانه.
{
  ok(looksLikeSchedule(SUMOUD), 'القديمُ يدّعي الكتابَ — بسبب «شعبة التجهيز»');
  ok(looksLikeOfficialTable(SUMOUD), 'والجديدُ يعرفه');
  // فالترتيبُ هو الفاصل: من سأل القديمَ أوّلاً مزّق الكتاب.
  const route = (text) => (looksLikeOfficialTable(text) ? 'official' : looksLikeSchedule(text) ? 'channel' : 'none');
  eq(route(SUMOUD), 'official', 'والجديدُ يسبق فيربح');
  eq(route(KIRKUK), 'official', 'وكذلك الثاني');
  eq(route('غدا ان شاء الله البنزين العادي في المحطات التالية\nالحق'), 'channel', 'ومنشورُ القناة يبقى للقناة');
  eq(route('محطة الحق'), 'none', 'واسمُ محطةٍ ليس واحداً منهما');
}

console.log(`✔ ${n} تحقّقاً — الكتابُ يُقرأ، والشرطةُ ليست طلبيّة، والتاريخُ من الوثيقة.`);
