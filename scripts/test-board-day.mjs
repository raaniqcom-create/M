// أيَّ يومٍ تعرضه اللوحة؟ — وماذا لو كان فارغاً وفي اليد جدول؟
//
// ── ليلةَ ٢٠٢٦-٠٩-٠٨ ──────────────────────────────────────────────────────
//
// نُشر جدولٌ من **ثلاثةٍ وأربعين** صفّاً الساعةَ ٢١:١٢ ببغداد على تاريخ اليوم.
// و`BOARD_FLIP_HOUR = 21`، فاللوحةُ كانت قد انقلبت إلى الغد قبل ذلك باثنتَي
// عشرةَ دقيقة. فقرأ الناسُ «لا جدولَ بعد» وفي القاعدة ثلاثةٌ وأربعون صفّاً
// عمرُها دقائق.
//
// ولم يكن خطأً في النشر: في البوت زرُّ 📅 يقلب التاريخ، ومنشورُ القناة قد
// يكون عن نهارٍ لم ينتهِ — فاختيارُ «اليوم» مقصود. والانقلابُ نفسُه صحيحٌ
// أيضاً: من يفتح الصفحةَ ليلاً يسأل عن الغد.
//
// **فالخطأُ في أنّ الترجيحَ كان يُطبَّق بلا نظرٍ في المرجَّح إليه.** ومن رجّح
// إلى يومٍ لا شيءَ فيه وتركَ يوماً مملوءاً فقد رجّح ضدّ قارئه.
import assert from 'node:assert/strict';

const BOARD_FLIP_HOUR = 21;
const TODAY = '2026-09-08';
const TOMORROW = '2026-09-09';

const boardDate = (hour) => (hour >= BOARD_FLIP_HOUR ? TOMORROW : TODAY);

/** مرآةُ `resolveBoardDay` في lib/board.ts. */
const resolve = (hour, schedule) => {
  const want = boardDate(hour);
  if (schedule.some((r) => r.for_date === want)) return want;
  if (TODAY !== want && schedule.some((r) => r.for_date === TODAY)) return TODAY;
  return want;
};

const rows = (day, n) => Array.from({ length: n }, () => ({ for_date: day }));

let n = 0;
const ok = (cond, what) => { assert.ok(cond, what); n++; };

// ── ١ · الحالُ السويّة: لا يتغيّر شيء ────────────────────────────────────
{
  const both = [...rows(TODAY, 13), ...rows(TOMORROW, 20)];
  ok(resolve(14, both) === TODAY, 'الثانيةَ ظهراً وفي اليد اليومان → اليوم');
  ok(resolve(22, both) === TOMORROW, 'العاشرةَ مساءً وفي اليد اليومان → الغد');
  ok(resolve(20, both) === TODAY, 'الثامنةَ مساءً — قبل الانقلاب بساعة → اليوم');
  ok(resolve(21, both) === TOMORROW, 'التاسعةَ تماماً → ينقلب');
}

// ── ٢ · الليلةُ التي كشفت العطب ──────────────────────────────────────────
//
// وهذا القسمُ **يسقط قبل الإصلاح**: `boardDate` وحدَها تردّ الغد، والغدُ خالٍ.
{
  const only43Today = rows(TODAY, 43);
  ok(boardDate(21) === TOMORROW, 'الترجيحُ نفسُه: بعد التاسعة الغد');
  ok(
    resolve(21, only43Today) === TODAY,
    'وقد خلا الغدُ وفي اليد ٤٣ صفّاً لليوم → تُعرض ولا تُخفى'
  );
  ok(resolve(23, only43Today) === TODAY, 'وكذلك الحادية عشرة');
  ok(resolve(21.5 | 0, only43Today) === TODAY, 'وكذلك التاسعة والنصف');
}

// ── ٣ · ولا يُقلب الترجيحُ حيث لا داعي ───────────────────────────────────
{
  ok(
    resolve(22, rows(TOMORROW, 30)) === TOMORROW,
    'جدولُ الغد موجودٌ واليومُ خالٍ → الغد، كما ينبغي'
  );
  ok(resolve(22, []) === TOMORROW, 'ولا جدولَ أصلاً → يبقى المرجَّح، والصفحةُ تقول «لا جدولَ بعد»');
  ok(resolve(10, []) === TODAY, 'وصباحاً بلا جدول → اليوم');
  // **والرجوعُ في اتّجاهٍ واحد، عمداً.** يفكّ الانقلابَ ولا يخترع قفزةً
  // أمامية: صباحاً وجدولُ الغد وحدَه منشور تبقى اللوحةُ على اليوم ولو خلا.
  //
  // وهذا قرارٌ قائمٌ في المشروع لا اجتهادٌ هنا — `HOUR_FLOOR` في
  // `TomorrowScreen`: «جدولُ الغد لا يُعرض قبل الثامنة مساءً كي لا يفاجئ
  // نشرٌ نهاريٌّ أحداً في وسط يومه». فلو رجع هذا في الاتّجاهين لنقض ذلك
  // الحارسَ من حيث لا يُنظر إليه.
  //
  // وكُتب هذا الفحصُ أوّلاً يتوقّع الغد، فسقط — وكان التوقّعُ هو الخطأ.
  ok(
    resolve(10, rows(TOMORROW, 9)) === TODAY,
    'صباحاً وجدولُ الغد وحدَه منشور → تبقى اللوحةُ على اليوم، ولا تسبق الثامنة مساءً'
  );
  ok(
    resolve(21, rows(TOMORROW, 9)) === TOMORROW,
    'وبعد التاسعة يُعرض الغد على بابه لا من خلفه'
  );
}

// ── ٤ · والعنوانُ يتبع المعروض ───────────────────────────────────────────
//
// «محطات اليوم» و«محطات غداً» تُشتقّان من اليوم المحسوم لا من المرجَّح — وإلا
// قرأ الفاتحُ عنواناً في القائمة وغيرَه في الصفحة.
{
  const title = (day) => (day === TODAY ? 'محطات اليوم' : 'محطات غداً');
  ok(title(resolve(21, rows(TODAY, 43))) === 'محطات اليوم', 'ليلةَ الحادثة: العنوان «محطات اليوم»');
  ok(title(boardDate(21)) === 'محطات غداً', 'ولو تُرك على المرجَّح لقال «غداً» عن صفوف اليوم');
}

console.log(`✔ ${n} حالة — واللوحةُ لا تنقلب إلى فراغٍ وفي اليد جدول.`);
