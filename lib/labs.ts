'use client';

/** ميزاتٌ تحت التجربة — تُشغَّل بمفتاحٍ في الإعدادات، لا بنشرٍ للجميع.
 *
 *  «مساعد الطريق» جاهز، ولم يُعلَن بعد. وبين الجاهز والمعلَن مسافةٌ يقطعها
 *  المالك وحده: يُشغّله فيجرّبه على هاتفه، ويُطفئه فيعود التطبيق كما كان
 *  للناس. فلا فرعٌ يُبنى ولا نشرٌ يُؤجَّل — سطرٌ في التخزين المحلّي.
 *
 *  وهو محلّيٌّ لكل جهاز عن قصد: تشغيلُه على هاتف المالك لا يُظهره لأحد،
 *  فليس علماً في قاعدة البيانات يُقرأ عند كل زيارة. وحين يُعلَن، يُحذف هذا
 *  الملفّ ويبقى البند ظاهراً للجميع.
 */

const KEY = 'muhta.labs.road';

/** يُقرأ في المتصفّح وحده: التصدير الساكن يُبنى على خادمٍ بلا localStorage،
 *  وأي قراءةٍ وقت التصيير تُنتج فرقاً بين ما بُني وما رُسم — وهو ما يُسقط
 *  شجرة React. فالافتراض «مطفأ» حتى يُقرأ من الجهاز. */
export function roadEnabled(): boolean {
  if (typeof window === 'undefined') return false;
  try {
    return localStorage.getItem(KEY) === '1';
  } catch {
    // متصفّحٌ يمنع التخزين — تُقرأ كإطفاء، ولا تُسقط الصفحة.
    return false;
  }
}

export function setRoadEnabled(on: boolean): void {
  try {
    if (on) localStorage.setItem(KEY, '1');
    else localStorage.removeItem(KEY);
  } catch {
    /* لا يضرّ */
  }
  // القائمة الجانبية تسمع هذا، فيظهر البند أو يختفي بلا إعادة تحميل.
  window.dispatchEvent(new Event('muhta:labs'));
}
