/** قوالبُ إشعارات المنصّة — ما يتكرّر يُكتب مرّةً ويُملأ.
 *
 *  **وسببُها انقطاعُ الإنترنت في الامتحانات.** يُقطع في عموم العراق ساعاتٍ
 *  معلومة، فلا تصل تحديثاتُ المحطات ولا تصل الإشعارات. والمنصّةُ تبدو حينها
 *  ساكتةً عن غير سبب — أو أسوأ: تعرض حالةً قديمةً كأنها الآن.
 *
 *  فالتنبيهُ قبل القطع بدقائق هو الحيلةُ الوحيدة الممكنة: بعده لا يصل شيء.
 *  ولذلك يُجدوَل، ولا يُترك لمن يتذكّره في الخامسة والنصف صباحاً.
 *
 *  وهذه نصوصٌ ابتدائية تُملأ وتُحرَّر — لا قيود. الغرضُ ألّا يُكتب النصُّ
 *  نفسُه من الصفر كلَّ صباحٍ طوال موسم الامتحانات. */

export interface NoticeVars {
  /** ساعةُ القطع كما تُقال: «6:00 صباحاً» */
  cutAt: string;
  /** مدينةُ التوزيع: «الرمادي» */
  city: string;
  /** ساعةُ التوزيع: «6:30» */
  distAt: string;
  /** نصٌّ حرٌّ يُضاف — سببُ الاعتذار مثلاً */
  note: string;
  /** المحطةُ التي يُظنّ أنّها توزّع اليوم: «محطة تعبئة وقود الرمادي الجديدة» */
  station: string;
  /** اسمُ الوقود كما يُقرأ: «بانزين عادي» — فارغٌ يعني كلَّ الوقود */
  product: string;
}

export interface NoticeTemplate {
  key: string;
  /** اسمُه على الزرّ */
  name: string;
  title: (v: NoticeVars) => string;
  body: (v: NoticeVars) => string;
  /** أيُّ الحقول تُعرض لهذا القالب */
  fields: (keyof NoticeVars)[];
  /** كم ساعةً يبقى معروضاً في «الأخبار» بعد إرساله */
  hours: number;
  /** ساعةُ الإرسال المقترحة غداً — «05:55» لتنبيهِ قطعِ السادسة */
  suggest: string | null;
  /** ما يُشرح تحت الزرّ */
  hint: string;
  /** `city`: يصل مدينةَ المحطة وحدَها (عبر alerts_for) لا كلَّ جهاز — ويُرسل
   *  فوراً بلا حاجز الخمس والأربعين دقيقة، فمن وصله إشعارُ محطةٍ قبل قليل
   *  هو بعينه الواقفُ في طابورها الآن. */
  scope?: 'city';
  /** أقصى طولٍ للمتن: خبرُ المدينة يُقصّ عند ١٧٨ حرفاً في الإشعار. */
  maxBody?: number;
}

/** اسمُ يوم الغد بتقويم بغداد: «الأربعاء». */
export function tomorrowName(): string {
  return new Date(Date.now() + 86_400_000).toLocaleDateString('ar-IQ', {
    timeZone: 'Asia/Baghdad',
    weekday: 'long',
  });
}

