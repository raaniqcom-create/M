/** المحطاتُ الحكوميّة بأسمائها وعناوينها الرسميّة — كما أملاها صاحبُ المنصّة
 *  (١٥ أيلول ٢٠٢٦) لتصحيح ما يُعرض في جدول التوزيع.
 *
 *  ── لماذا قائمةٌ بيدِ إنسان ─────────────────────────────────────────────
 *
 *  كتابُ الفرع يكتب الاسمَ مع اسمِ المدينة وبقيّةِ الوقود في خانةٍ واحدة:
 *  «طليحة الحكومية الرمادي وكاز» — ومحطةُ طليحة على الكيلو ١٦٠ في الرطبة لا
 *  في الرمادي. وقائمةُ المسح (`roadStations.ts`) مولَّدةٌ من خرائطَ مفتوحة
 *  تضع طليحةَ في كبيسة. فلا مصدرَ آليّاً يعرف المكانَ الصحيح؛ والذي يعرفه
 *  أملاه هنا.
 *
 *  **والمدينةُ هنا مدينةُ المنصّة** (`CITY_NAMES`) لا قضاءُ الكتاب: الناسُ
 *  يشتركون بـ«البغدادي» و«الحقلانية» و«الصقلاوية»، والإشعارُ يُرشَّح بها
 *  حرفاً بحرف. فـ«الجبل» في البغدادي وإن كتبها الكتابُ تحت هيت. */
export interface OfficialStation {
  name: string;
  city: string;
  address: string | null;
  /** إملاءٌ آخر يكتبه الكتابُ الرسميّ: «عانة» للاسم «عنة». */
  alt?: string[];
}

const S = (name: string, city: string, address: string | null, alt?: string[]): OfficialStation => ({
  name,
  city,
  address,
  ...(alt ? { alt } : {}),
});

