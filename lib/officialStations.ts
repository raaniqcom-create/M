const INDIC = '٠١٢٣٤٥٦٧٨٩';
const words = (t: string): string[] =>
  normalizeName(t.replace(/[٠-٩]/g, (ch) => String(INDIC.indexOf(ch))))
    .split(' ')
    .filter(Boolean);

/** كلماتُ المدن كلِّها — تَرِد في سطر الكتاب بجانب الاسم ولا تخصّه. */
export const CITY_WORDS: ReadonlySet<string> = new Set([
  ...CITY_NAMES.flatMap((c) => words(c)),
  ...words('عانة الأنبار'),
]);

/** ما يَرِد في السطر ولا يميّز محطةً: صفةُ الملكيّة، وبقايا الوقود الآخر،
 *  وكلماتُ الوصف («قرب»، «مركز»، «الناحية»). */
const FILLER = new Set(
  words(
    'الحكومية الاهلية وكاز كاز ونفط نفط ابيض وغاز غاز عادي محسن يم عند قرب مركز المركز ' +
      'المدينة مدينة القضاء قضاء الناحية ناحية قرية طريق الطريق العام الخارجي سيطرة'
  )
);

interface Entry {
  s: OfficialStation;
  names: Set<string>[];
  addr: Set<string>;
}

const ENTRIES: Entry[] = OFFICIAL_STATIONS.map((s) => ({
  s,
  names: [s.name, ...(s.alt ?? [])].map((n) => new Set(words(n))),
  addr: new Set(words(s.address ?? '')),
}));

/** المحطةُ الرسميّةُ التي يسمّيها هذا النصّ — أو لا شيء.
 *
 *  ── القاعدة ─────────────────────────────────────────────────────────────
 *
 *  كلماتُ الاسم الرسميّ **كلُّها** في النصّ، وما زاد في النصّ إمّا مدينةٌ
 *  أو حشوٌ أو كلمةٌ من العنوان. فـ«طليحة الحكومية الرمادي وكاز» تطابق طليحة
 *  (والرماديُّ زائدةٌ مدينة)، و«الكعبيات الحكومية القائم» **لا** تطابق «القائم
 *  الحكومية» لأنّ «الكعبيات» زائدةٌ ليست مدينةً ولا حشواً.
 *
 *  وإن لم يُسمِّ النصُّ محطةً وسمّى عنوانَها وحدَه — «الامن»، «السينما» كما
 *  تكتب القناة — طابق بالعنوان، شرطَ أن يكون العنوانُ لمحطةٍ واحدة: «٥ كيلو»
 *  عنوانُ اثنتين فلا يُحسم.
 *
 *  والتباسُ أكثر من محطةٍ يُردّ بلا جواب: التخمينُ أسوأُ من الصمت. */
export function officialFor(text: string): OfficialStation | null {
  const c = new Set(words(text));
  if (!c.size) return null;

  let best: Entry[] = [];
  let bestSize = 0;
  for (const e of ENTRIES) {
    for (const nm of e.names) {
      if (!nm.size) continue;
      let all = true;
      for (const w of nm) if (!c.has(w)) { all = false; break; }
      if (!all) continue;
      // واسمٌ هو اسمُ مدينةٍ («القائم الحكومية») لا يقبل مدينةً أخرى زائدة:
      // «الكرابلة الحكومية القائم» محطةُ الكرابلة لا محطةُ القائم، والكرابلةُ
      // مدينةٌ في القائمة فكانت ستمرّ «مدينةً زائدة».
      let nmAllCity = true;
      for (const w of nm) if (!CITY_WORDS.has(w) && !FILLER.has(w)) { nmAllCity = false; break; }
      let clean = true;
      for (const w of c) {
        if (nm.has(w) || FILLER.has(w) || e.addr.has(w)) continue;
        if (CITY_WORDS.has(w) && !nmAllCity) continue;
        clean = false;
        break;
      }
      if (!clean) continue;
      if (nm.size > bestSize) {
        best = [e];
        bestSize = nm.size;
      } else if (nm.size === bestSize && !best.includes(e)) best.push(e);
    }
  }
  if (best.length === 1) return best[0].s;
  if (best.length > 1) return null;

  // بالعنوان وحدَه — العنوانُ كلُّه، لمحطةٍ واحدةٍ لا أكثر. «الجزيرة» وحدَها
  // ليست «الجزيرة، البو علي»: نصفُ عنوانٍ يقع على نصف المدينة.
  const meaningful = new Set([...c].filter((w) => !CITY_WORDS.has(w) && !FILLER.has(w)));
  if (!meaningful.size) return null;
  const byAddr = ENTRIES.filter((e) => {
    const core = [...e.addr].filter((w) => !CITY_WORDS.has(w) && !FILLER.has(w));
    return core.length === meaningful.size && core.every((w) => meaningful.has(w));
  });
  return byAddr.length === 1 ? byAddr[0].s : null;
}
