/** منافذُ مدن القارئ (المؤكَّدُ أوّلاً) — والفارغُ الكلّ. */
export function outletsFor(cities: string[] | null | undefined): { mine: CanOutlet[]; rest: CanOutlet[] } {
  const all = [...CANS.confirmed, ...CANS.candidates];
  if (!cities?.length) return { mine: [], rest: all };
  const set = new Set(cities);
  const mine = all.filter((o) => o.cities.some((c) => set.has(c)));
  return { mine, rest: all.filter((o) => !mine.includes(o)) };
}
