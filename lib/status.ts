/** مفتاحُ إيقاف الموقع — ملفٌّ على الموقع نفسِه، لا رايةٌ في القاعدة.
 *
 *  ── لماذا ملفّ ───────────────────────────────────────────────────────────
 *
 *  أوّلُ استعمالٍ لهذا المفتاح نقلُ قاعدة البيانات إلى منطقةٍ أقرب. ورايةٌ في
 *  القاعدة تحتاج، لتُقرأ، ما يكون متوقّفاً في تلك اللحظة بعينها. فالملفُّ
 *  يُشحن مع الموقع الساكن ويُقرأ ولو كانت القاعدةُ مطفأةً تماماً.
 *
 *  ── ومفتاحٌ يُطفئ نفسه ──────────────────────────────────────────────────
 *
 *  `until` ليست زينة. المفتاحُ يُقلب في وقتٍ حرج، وطريقُ إطفائه — لوحةُ
 *  الإدارة — هو نفسُه ما قد يكون معطّلاً. فالانتهاءُ محسوبٌ في القراءة: صيانةٌ
 *  قُلبت الثالثةَ فجراً ونُسيت تنتهي وحدَها.
 *
 *  ── والافتراضُ أن الموقع يعمل ────────────────────────────────────────────
 *
 *  ملفٌّ مفقود، أو ٤٠٤، أو JSON مكسور — كلُّها تعني «ليست صيانة». المفتاحُ
 *  يُطفئ الموقعَ بقصدٍ صريحٍ فقط، ولا يُطفئه عطلٌ في نفسه.
 */
export type SiteStatus = {
  maintenance: boolean;
  /** ISO — بعده يعود الموقع من تلقائه. فارغةٌ تعني «لا صيانة». */
  until: string;
  message: string;
};

export function isDown(s: SiteStatus | null, now = Date.now()): boolean {
  if (!s?.maintenance || !s.until) return false;
  const t = new Date(s.until).getTime();
  return Number.isFinite(t) && t > now;
}

/** **`no-store` لا زينةً.** GitHub Pages يخدم كلَّ ملفّ بـ`max-age=600`، فبلا
 *  هذا تتأخّر الصيانةُ عشرَ دقائق في الظهور وعشراً في الزوال — على طرفَي
 *  النافذة معاً. ومعه استثناءٌ في `public/sw.js` كي لا يردّ العاملُ نسخةً
 *  قديمةً قبل أن تصل الشبكةُ أصلاً.
 *
 *  ولا يُكسر الخزنُ بـ`?t=`: عنوانٌ فريدٌ لكلّ فتحةٍ يعني مدخلاً في مخزن
 *  العامل لكلّ فتحة — مخزنٌ بلا سقف، وهو أسوأُ من العلّة. */
export async function readStatus(): Promise<SiteStatus | null> {
  try {
    const r = await fetch('/status.json', { cache: 'no-store' });
    return r.ok ? ((await r.json()) as SiteStatus) : null;
  } catch {
    return null;
  }
}
