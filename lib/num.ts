/** رقمٌ يُقرأ بلمحة.
 *
 *  «125273 زائر» تُقرأ رقماً طويلاً لا عدداً؛ و«125,273» تُقرأ «مئةً وخمسةً
 *  وعشرين ألفاً» في لمحة. والفاصلةُ ليست زينةً بل هي ما يجعل الرقم عدداً.
 *
 *  **وبأرقامٍ لاتينيّة لا هنديّة.** المنصّةُ كلُّها تعرض الأرقامَ لاتينيّةً —
 *  العدّادات، وساعاتُ الدوام، وأرقامُ الهواتف — فـ`ar-IQ` هنا كانت ستُخرج
 *  «١٢٥٬٢٧٣» فيصير في الشاشة الواحدة نظامان.
 *
 *  ونصٌّ فارغٌ لمن لا رقمَ له بعد: صفرٌ يُقرأ خبراً، وهو ليس خبراً. */
export function num(n: number | null | undefined): string {
  return typeof n === 'number' && Number.isFinite(n) ? n.toLocaleString('en-US') : '—';
}
